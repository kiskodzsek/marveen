#!/usr/bin/env python3
"""PreToolUse gate (telegram reply + edit_message): no "can PR #<n> go live?" message without a per-file check.

Why (shared/hibanaplo.md 2026-11-11 07:3x, Klodel 37320): Klodel asked Patrik to ship PR #1273 with a picture of
ONE section (TG 4817), while the PR also changed the title/lead of two other pages. Patrik said OK (TG 4820);
Klodel withdrew it himself (TG 4823). The ask covered what the asker remembered, not what the PR changes.

What triggers: a reply / edit whose text names a PR number ("PR #1273", "PR 1273", "PR-1273", "#1273",
"1273-as PR") AND asks or tells about shipping it (éles..., mehet, kimehet, kerülhet, deploy, kiad..., merge,
beolvaszt..., promote, publik..., jóváhagy..., indulhat, go live, ship). Matching runs over normalised text: NFKD
with the accents dropped, lower case, zero-width characters removed. A "#<number>" of something else next to a
shipping word ("msg #37334 mehet") triggers too: a false alarm the escape line below settles.

What it needs, per PR number n: store/pr-kerdes/<n>.ok, generated by scripts/pr-kerdes.py from the GitHub API
(the full file list of the PR, not a list typed from memory), then filled in by hand:
    REPO: kiskodzsek/<repo>
    PR: <n>
    HEAD: <40-hex head sha at generation>
    GENERALT: <UTC ISO time of generation>          at most PR_KERDES_MAX_AGE_H hours old (default 12)
    LISTA: <file count> <sha256 of the sorted paths, one per line>
    FILE: <path> | KEPEN: igen <absolute image path>
    FILE: <path> | KEPEN: nem-vevoi <why no customer sees this file change, at least 10 characters>
Every FILE line needs a KEPEN answer; the FILE set must hash to LISTA (a dropped or added line is caught); every
"igen" image must exist, be an image, and be attached to THIS message (`files`), so the ask carries a picture of
every customer-visible change.

Escape for a message that names a PR and a shipping word but asks nothing (e.g. "the #1273 is live"): a line
    PR-KERDES: nem-keres <why, at least 15 characters>
It is written into the message, so the owner sees the claim; it is not a way around an ask.

Limits (said out loud, not hidden): the hook runs offline, with no GitHub token, so it cannot see a push made after
the .ok was generated; GENERALT bounds that window, and the person asking regenerates after a new push. A PR named
without its number ("the gallery change") is not caught. Which files a customer sees is the writer's judgement;
the gate makes it a written, per-file statement. It is an accident-prevention gate, not an attacker-proof one
(Viktor 37340): the sheet is self-declared (whoever computes LISTA can pass a typed list), one picture can be
reused for every file, and other channels (an email to Patrik, an ask relayed by a colleague) are not covered.

Any error while checking blocks (exit 2); only an unreadable hook payload allows (nothing to check).
Tests: pr-kerdes-gate_test.py next to this file.
"""
import hashlib
import json
import os
import re
import sys
import time
import unicodedata
from datetime import datetime, timezone

ROOT = os.environ.get('CLAUDE_PROJECT_DIR', '/Users/klodel/marveen')
DIR = os.path.join(ROOT, 'store', 'pr-kerdes')
MAX_AGE_H = float(os.environ.get('PR_KERDES_MAX_AGE_H', '12'))
IMAGE_EXT = ('.png', '.jpg', '.jpeg', '.webp', '.gif')
REPO_RX = re.compile(r'^kiskodzsek/[A-Za-z0-9._-]+$')
HEAD_RX = re.compile(r'^[0-9a-f]{40}$')
LISTA_RX = re.compile(r'^(\d+)\s+([0-9a-f]{64})$')

# "PR #1273", "PR 1273", "PR-1273", "#1273", and the Hungarian "1273-as PR", "az 1273-as pr-t" (Viktor 37340).
PR_RXS = (
    re.compile(r'(?:\bpr\s*-?\s*#?\s*|\bpull request\s*#?\s*|#)(\d{1,6})\b'),
    re.compile(r'\b(\d{1,6})\s*-?\s*(?:as|es|os)?\s*(?:pr|pull request)\b'),
)
SHIP_RX = re.compile(r'\beles|\bmehet|\bkimehet|\bkerulhet|\bdeploy|\bkiad|\bmerge|\bbeolvaszt|\bpromote|\bpublik'
                     r'|\bjovahagy|\bindulhat|\bgo live|\bship')
ESCAPE = 'PR-KERDES: nem-keres'


def norm(text):
    t = unicodedata.normalize('NFKD', text or '')
    t = ''.join(c for c in t if not unicodedata.combining(c))
    t = re.sub('[​-‏⁠﻿]', '', t)
    return t.lower()


def pr_numbers(text):
    """PR numbers the text asks about shipping, or [] when it is not such a message."""
    t = norm(text)
    if not SHIP_RX.search(t):
        return []
    return sorted({int(m.group(1)) for rx in PR_RXS for m in rx.finditer(t)})


def escaped(text):
    for line in (text or '').splitlines():
        line = line.strip()
        if line.startswith(ESCAPE):
            return len(line[len(ESCAPE):].strip()) >= 15
    return False


def list_hash(paths):
    return hashlib.sha256('\n'.join(sorted(paths)).encode('utf-8')).hexdigest()


def parse(path):
    """(header dict, [(file path, kepen answer)]) of an .ok file."""
    head, files = {}, []
    with open(path, encoding='utf-8') as f:
        for raw in f:
            line = raw.strip()
            if not line or line.startswith('#'):
                continue
            if line.startswith('FILE:'):
                body = line[len('FILE:'):]
                if '| KEPEN:' in body:
                    p, k = body.split('| KEPEN:', 1)
                    files.append((p.strip(), k.strip()))
                else:
                    files.append((body.strip(), ''))
                continue
            if ':' in line:
                k, v = line.split(':', 1)
                head.setdefault(k.strip().upper(), v.strip())
    return head, files


def check(n, attached):
    """Error strings for PR n; [] = the ask may go."""
    path = os.path.join(DIR, f'{n}.ok')
    fix = (f'Generáld: GITHUB_PERSONAL_ACCESS_TOKEN=vault:github-github_personal_access_token '
           f'./scripts/vault-env-wrapper.sh python3 -I scripts/pr-kerdes.py init kiskodzsek/<repo> {n}, '
           f'utána a {path} minden FILE sorába KEPEN-t.')
    if not os.path.isfile(path):
        return [f'PR #{n}: nincs {path}. {fix}']
    head, files = parse(path)
    errs = []
    if not REPO_RX.match(head.get('REPO', '')):
        errs.append(f'PR #{n}: REPO hiányzik vagy nem kiskodzsek/<repo>.')
    if head.get('PR', '') != str(n):
        errs.append(f'PR #{n}: a lap PR sora "{head.get("PR", "")}", nem {n}.')
    if not HEAD_RX.match(head.get('HEAD', '')):
        errs.append(f'PR #{n}: HEAD nem 40 hex karakter.')
    try:
        gen = datetime.strptime(head.get('GENERALT', ''), '%Y-%m-%dT%H:%M:%SZ').replace(tzinfo=timezone.utc)
        age_h = (time.time() - gen.timestamp()) / 3600
        if age_h > MAX_AGE_H or age_h < -0.1:
            errs.append(f'PR #{n}: a lap {age_h:.1f} órás (max. {MAX_AGE_H:g}); azóta jöhetett új push. {fix}')
    except ValueError:
        errs.append(f'PR #{n}: GENERALT hiányzik vagy nem YYYY-MM-DDTHH:MM:SSZ. {fix}')
    m = LISTA_RX.match(head.get('LISTA', ''))
    paths = [p for p, _ in files]
    if not m:
        errs.append(f'PR #{n}: LISTA hiányzik. {fix}')
    elif int(m.group(1)) != len(paths) or len(set(paths)) != len(paths) or list_hash(paths) != m.group(2):
        errs.append(f'PR #{n}: a FILE sorok nem a generált fájllista (LISTA {m.group(1)} fájl, a lapon {len(paths)}); '
                    'sor nem törölhető, nem írható hozzá. ' + fix)
    if not files:
        errs.append(f'PR #{n}: nincs FILE sor. {fix}')
    att = {os.path.realpath(a) for a in attached}
    for p, k in files:
        kl = norm(k)
        if kl.startswith('igen'):
            img = k[len('igen'):].strip()
            if not img or not os.path.isabs(img):
                errs.append(f'PR #{n} {p}: KEPEN igen után abszolút képútvonal kell.')
            elif not img.lower().endswith(IMAGE_EXT) or not os.path.isfile(img):
                errs.append(f'PR #{n} {p}: a kép nem létezik vagy nem kép: {img}')
            elif os.path.realpath(img) not in att:
                errs.append(f'PR #{n} {p}: a kép ({os.path.basename(img)}) nincs csatolva ehhez az üzenethez (files).')
        elif kl.startswith('nem-vevoi'):
            if len(k[len('nem-vevoi'):].strip()) < 10:
                errs.append(f'PR #{n} {p}: "nem-vevoi" után indok kell (min. 10 karakter).')
        else:
            errs.append(f'PR #{n} {p}: nincs KEPEN válasz (igen <kép> | nem-vevoi <indok>).')
    return errs


def main():
    try:
        data = json.load(sys.stdin)
    except Exception:
        return 0
    try:
        ti = data.get('tool_input') or {}
        text = str(ti.get('text') or '')
        nums = pr_numbers(text)
        if not nums or escaped(text):
            return 0
        files = [str(f) for f in (ti.get('files') or [])]
        errs = [e for n in nums for e in check(n, files)]
    except Exception as e:  # fail-closed: a broken check must not let the ask through
        errs = [f'a kapu hibára futott ({type(e).__name__}); javítsd vagy szólj Kernelnek.']
    if not errs:
        return 0
    sys.stderr.write(
        'PR-KÉRDÉS-KAPU (hibanapló 2026-11-11, #1273: egy szakasz képével kértünk élesítést, a PR két másik oldalt '
        'is módosított): PR élesítéséről csak a PR TELJES fájllistájával és fájlonkénti képpel vagy indokkal írhatsz.\n'
        + '\n'.join('- ' + e for e in errs[:20])
        + (f'\n- ... és még {len(errs) - 20} hiba' if len(errs) > 20 else '')
        + f'\nHa az üzenet nem kér élesítést, egy sor: "{ESCAPE} <miért>".\n')
    return 2


if __name__ == '__main__':
    sys.exit(main())
