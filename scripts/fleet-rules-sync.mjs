#!/usr/bin/env node
// fleet-rules-sync (FLEETRULESSYNC1015, card 834a0364): rebuilds the
// install-local fleet rules (store/fleet-rules.md) from the root CLAUDE.md and
// stamps them, so an edit of the root does not leave the opted-in agents on the
// full root load until someone re-syncs by hand.
//
// Every level-2 heading of the root must be classified in store/fleet-rules-map.json:
//   fleet       copied VERBATIM into the rules file (placeholders substituted)
//   agent_file  the agents carry it in their own CLAUDE.md (scaffold blocks)
//   main_only   the main agent's own business (persona, morning brief...)
// A heading matches an entry by prefix, because the root headings carry dates.
// An UNCLASSIFIED heading, or a fleet entry the root no longer has, stops the
// sync: nothing is written and the old stamp stays, so the opted-in agents keep
// loading the root (the safe direction). The decision -- does the new rule
// belong to the sub-agents? -- is a human one; recording it is one line in the map.
//
// Usage (from the install root, or pass --root):
//   node scripts/fleet-rules-sync.mjs           build, write, stamp
//   node scripts/fleet-rules-sync.mjs --check   exit 0 if the rules file is the build of the current root and stamped
//   node scripts/fleet-rules-sync.mjs --print   print the build to stdout, write nothing
// Exit: 0 ok / in sync, 1 needs a decision or out of sync, 2 cannot run.
//
// Map format (see templates/fleet-rules-map.example.json):
//   { "fleet": ["Heading prefix", {"heading": "...", "stop_at": "H3 prefix"},
//               {"h3": "H3 prefix", "title": "H2 title to render it under"}],
//     "agent_file": [...], "main_only": [...],
//     "substitutions": [["from", "to"], ...] }
import { readFileSync, writeFileSync, renameSync, existsSync, statSync, chmodSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { join, dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { spawnSync } from 'node:child_process'

const HERE = dirname(fileURLToPath(import.meta.url))

export const HEADER = `<!--
  Fleet rules: the owner's rules that every SUB-agent must carry.

  Generated by scripts/fleet-rules-sync.mjs from the root CLAUDE.md and
  store/fleet-rules-map.json -- do not edit by hand, edit the root and re-sync.
  Rendered by ensureFleetRulesSection() (src/web/agent-scaffold.ts) into the
  CLAUDE.md of every agent whose agent-config.json sets "excludeRootClaudeMd": true.

  Placeholders: {{AGENT_ID}}, {{PROJECT_ROOT}}, {{DASHBOARD_ORIGIN}}.
-->
`

// Headings outside code fences, with their line index.
function headings(lines) {
  const out = []
  let fence = false
  lines.forEach((ln, i) => {
    if (ln.trimStart().startsWith('```')) { fence = !fence; return }
    if (fence) return
    const m = /^(#{1,6}) (.*)$/.exec(ln)
    if (m) out.push({ i, level: m[1].length, title: m[2].trim() })
  })
  return out
}

const prefixOf = (entry) => (typeof entry === 'string' ? entry : entry.heading ?? entry.h3)

// The lines of the section that starts at heading h, up to the next heading of
// level <= h.level (or, with stopAt, the first sub-heading starting with it).
function sectionLines(lines, heads, h, stopAt) {
  const next = heads.find((x) => x.i > h.i && (x.level <= h.level || (stopAt && x.title.startsWith(stopAt))))
  return lines.slice(h.i, next ? next.i : lines.length)
}

export function build(rootText, map) {
  const lines = rootText.split('\n')
  const heads = headings(lines)
  const h2 = heads.filter((h) => h.level === 2)
  const problems = []
  const classified = [...map.fleet, ...(map.agent_file ?? []), ...(map.main_only ?? [])]
    .filter((e) => typeof e === 'string' || e.heading)
    .map(prefixOf)
  for (const h of h2) {
    if (!classified.some((p) => h.title.startsWith(p))) problems.push(`unclassified root section: "## ${h.title}"`)
  }
  const parts = []
  for (const entry of map.fleet) {
    const prefix = prefixOf(entry)
    if (typeof entry === 'object' && entry.h3) {
      const h = heads.find((x) => x.level === 3 && x.title.startsWith(prefix))
      if (!h) { problems.push(`fleet entry not in the root: "### ${prefix}"`); continue }
      const body = sectionLines(lines, heads, h).slice(1).join('\n').replace(/^\n+/, '')
      parts.push(`## ${entry.title}\n\n${body}`)
      continue
    }
    const found = h2.filter((x) => x.title.startsWith(prefix))
    if (found.length !== 1) {
      problems.push(found.length ? `fleet entry matches ${found.length} root sections: "${prefix}"` : `fleet entry not in the root: "## ${prefix}"`)
      continue
    }
    parts.push(sectionLines(lines, heads, found[0], typeof entry === 'object' ? entry.stop_at : undefined).join('\n'))
  }
  let body = parts.map((p) => p.replace(/\s+$/, '') + '\n').join('\n')
  for (const [from, to] of map.substitutions ?? []) body = body.split(from).join(to)
  return { text: `${HEADER}\n${body}`, problems }
}

// The rules file without its leading comment (the stamp lives there).
const bodyOf = (text) => text.replace(/^\s*<!--[\s\S]*?-->\s*/, '')

function writeAtomic(path, content) {
  const tmp = `${path}.tmp-${process.pid}`
  writeFileSync(tmp, content)
  chmodSync(tmp, existsSync(path) ? statSync(path).mode & 0o777 : 0o600)
  renameSync(tmp, path)
}

function main(argv) {
  const opt = (flag) => { const i = argv.indexOf(flag); return i >= 0 ? argv[i + 1] : undefined }
  const root = resolve(opt('--root') ?? join(HERE, '..'))
  const rulesPath = join(root, 'store', 'fleet-rules.md')
  const mapPath = join(root, 'store', 'fleet-rules-map.json')
  let rootText, map
  try {
    rootText = readFileSync(join(root, 'CLAUDE.md'), 'utf-8')
    map = JSON.parse(readFileSync(mapPath, 'utf-8'))
    if (!Array.isArray(map.fleet)) throw new Error('fleet-rules-map.json: "fleet" is not a list')
  } catch (e) {
    console.error(`fleet-rules-sync: cannot run: ${e.message}`)
    return 2
  }
  const { text, problems } = build(rootText, map)
  if (problems.length) {
    for (const p of problems) console.error(`fleet-rules-sync: ${p}`)
    console.error('fleet-rules-sync: NOT synced -- classify the section in store/fleet-rules-map.json (fleet / agent_file / main_only); until then the opted-in agents keep loading the root CLAUDE.md')
    return 1
  }
  if (argv.includes('--print')) { process.stdout.write(text); return 0 }
  const stamp = join(HERE, 'fleet-rules-stamp.mjs')
  if (argv.includes('--check')) {
    const current = existsSync(rulesPath) ? readFileSync(rulesPath, 'utf-8') : ''
    if (bodyOf(current) !== bodyOf(text)) {
      console.log(`STALE: ${rulesPath} is not the build of the current root -- run node scripts/fleet-rules-sync.mjs`)
      return 1
    }
    const r = spawnSync(process.execPath, [stamp, '--root', root, '--check'], { encoding: 'utf-8' })
    process.stdout.write(r.stdout ?? '')
    return r.status === 0 ? 0 : 1
  }
  const sha = createHash('sha256').update(text).digest('hex').slice(0, 12)
  writeAtomic(rulesPath, text)
  const r = spawnSync(process.execPath, [stamp, '--root', root], { encoding: 'utf-8' })
  process.stdout.write(r.stdout ?? '')
  process.stderr.write(r.stderr ?? '')
  if (r.status !== 0) return 2
  console.log(`fleet-rules-sync: wrote ${rulesPath} (${Buffer.byteLength(text)} B, build ${sha}) and stamped it`)
  return 0
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = main(process.argv.slice(2))
}
