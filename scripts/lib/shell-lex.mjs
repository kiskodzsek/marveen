// shell-lex.mjs -- ONE shell lexer for the command gates (card fae0712e, DREAM 11-15).
//
// Why: bash-egress-parser.mjs (+ self-pace-gate.mjs maskInertLiterals), src/web/schedule-trust.ts (shCodeMask) and
// scripts/hooks/keychain-read-gate.py each lexed shell text by hand. In 48 hours 29 Viktor verdicts were about two of
// them, 9 HIGH/MEDIUM, and the same class (quote, comment, heredoc, prefix) came back gate by gate. This module is the
// one place that knows where a quote, a comment, a heredoc body or a substitution starts and ends. Its Python twin is
// scripts/lib/shell_lex.py; both must give the SAME answer on scripts/lib/shell-lex-golden.json (both test files
// check it), so the two cannot drift apart. Both are also checked against a real bash: scripts/lib/shell-lex-oracle.json
// (generated by shell-lex-oracle-gen.py) holds commands with marker commands and the markers bash ran, and a marker
// must run iff the lexer makes it a command word (Viktor 42697: two lexers agreeing cannot catch a shared mistake).
//
// It does not judge anything. A gate asks it what each character IS and keeps its own rules.
//
// lex(text) -> {
//   cls:      string, one class letter per code POINT of text (Array.from(text)); see CLS below.
//   problems: string[]; non-empty = the text is not fully understood (unterminated quote, heredoc, substitution, or a
//             heredoc inside a substitution, whose body bash 3.2, bash 5 and zsh read differently). A gate that may
//             LOOSEN on what it read must not loosen when problems is non-empty.
//   heredocs: [{op, opEnd, delim, quoted, stripTabs, bodyStart, bodyEnd, end}], code-point indices: op = the
//             first `<` of `<<`, opEnd = just past the delimiter word, body = [bodyStart, bodyEnd), the terminator line
//             is [bodyEnd, end). Only top-level heredocs: one inside a substitution is a problem, its lines stay code.
//   substs:   [{kind, start, end, inner}] kind '$(', '`', '<(', '>(', '(', '$((', '((', '${'; start = first char of
//             the opener, end = just past the closer (text length if unterminated); inner = [innerStart, innerEnd).
//   segments: [{start, end, depth}] simple commands: maximal code runs between separators (; & && || | |& newline) in
//             one frame; a nested $( ) ` ` <( ) >( ) $(( )) ${ } is part of the segment's word, a bare ( ) or (( ))
//             is its own command and is left out; trimmed, never empty. depth 0 = top level. Every frame gets its
//             own segments, $(( )) (( )) and ${ } too: over-reporting a command is the safe side (bash falls back
//             from $(( to $( (, and bash 5.3 runs ${ cmd; }).
//             frame = the kind of the frame the segment is in ('top' or a substs kind), frameAt = its index in
//             substs (-1 = top): a gate that knows a frame runs no command (arithmetic) can skip it there.
//             A redirection stays in a word (2>&1, >f, <<'E'); words() does not split at < or >.
// }
// words(text, lx, seg) -> [{text, start, end, quoted, expands}] the shell words of a segment, quotes removed
// (backslash pairs reduced, a backslash-newline removed, $'...' decoded by ansiC), expands = an unquoted or
// double-quoted $ or ` in it. A substitution stays verbatim inside its word.
//
// CLS (one letter per code point):
//   c code; q '...' (quotes included); a $'...' ($ and quotes included); d "..." literal part (quotes included; a
//   $(...) or `...` inside is c again); e a backslash pair (both chars); l a backslash-newline (both chars);
//   m a comment (# to the end of its line, the newline excluded); h a body of a heredoc with a quoted delimiter
//   (inert text); u a body with an unquoted delimiter ($, ` and \ are live there); t a terminator line.

const SEP = new Set([';', '&', '|', '\n'])
const META = new Set([' ', '\t', '\n', ';', '&', '|', '(', ')', '<', '>'])
const NO_COMMENT_KINDS = new Set(['${', '$((', '(('])
const WORD_START_BEFORE = new Set([' ', '\t', '\n', ';', '&', '|', '(', ')', '<', '>'])
// Viktor 42852 HIGH 3: the closer of $( ), <( ), >( ), $(( )) and a backtick is word text, so a '#' right after it is
// word text too (echo $(true)#; b runs b). A plain ( ) subshell and the (( )) command end a word: (true)# is a comment.
const WORD_SUBST_KINDS = new Set(['$(', '<(', '>(', '$((', '`'])

// bash 3.2 reads $(( and (( as arithmetic only while the parentheses inside pair up and the frame ends in )): a ')'
// at depth 0 that is not followed by ')' makes the frame a subshell inside ($((a) ) runs a, measured). The lexer
// then reads that opener again as two parentheses ('split'); each retry splits one more opener, so it ends.
// Viktor 42888 LOW: one retry per such opener re-lexes the whole text, so many of them were quadratic (8000 took 6.4 s).
// Past MAX_SPLIT_RETRIES every $(( and (( is read as two parentheses at once: its body is read as commands, which
// shows a gate more, not less.
const MAX_SPLIT_RETRIES = 64
export function lex(text) {
  const split = new Set()
  for (let k = 0; k < MAX_SPLIT_RETRIES; k++) {
    const r = lexOnce(text, split)
    if (r.retry === undefined) return r
    split.add(r.retry)
  }
  return lexOnce(text, { has: () => true })
}

function lexOnce(text, split) {
  const s = Array.from(text)
  const n = s.length
  const cls = new Array(n).fill('c')
  const problems = []
  const heredocs = []
  const substs = []
  const pending = []           // heredocs whose body starts at the next code newline
  const stack = [{ kind: 'top' }]
  const top = () => stack[stack.length - 1]
  const inCode = () => top().kind !== '"'
  // the backtick frames on the stack as [index, frame], innermost last. Frames leave the stack in many places, so the
  // list is trimmed when read: an entry whose index is past the stack or holds another frame is gone, and so is every
  // entry above it. Walking the whole stack per character instead was quadratic (20 000 open '(' took 2.4 s, the
  // Python port 35 s; the keychain gate's timing paddings).
  const bts = []
  const liveBts = () => {
    while (bts.length) {
      const [k, g] = bts[bts.length - 1]
      if (k < stack.length && stack[k] === g) break
      bts.pop()
    }
    return bts
  }
  let i = 0

  const openSubst = (kind, start, innerStart, nested = false) => {
    const sub = { kind, start, end: n, inner: [innerStart, n] }
    substs.push(sub)
    const fr = { kind, sub, depth: 0, nested }
    // an escaped-backtick frame (nested) has no body end of its own: the next escaped backtick closes it, and the
    // outer body's end (its first unescaped backtick) ends it too, as an unterminated frame (bash: echo `a \` b` ; ls
    // runs ls at the top)
    if (kind === '`' && !nested) {
      // bash 3.2 cuts a backtick body out FIRST: it ends at the first unescaped backtick, whatever quote or $( ) is
      // open inside it (echo `echo '` ; curl runs curl). Quotes and comments in the body end there too.
      let j = innerStart
      while (j < n && s[j] !== '`') j += s[j] === '\\' ? 2 : 1
      fr.bodyEnd = j
      liveBts().push([stack.length, fr])
    }
    stack.push(fr)
  }
  const wordCloser = new Set()  // index of the last char of a closed word substitution (WORD_SUBST_KINDS)
  const closeSubst = (innerEnd, end) => {
    const f = stack.pop()
    f.sub.inner[1] = innerEnd
    f.sub.end = end
    if (WORD_SUBST_KINDS.has(f.kind)) wordCloser.add(end - 1)
  }

  const readHeredocBodies = (from) => {  // from = index just past a code newline; returns the next index to lex
    let p = from
    for (const h of pending.splice(0)) {
      h.bodyStart = p
      let found = false
      while (p < n) {
        let e = p
        while (e < n && s[e] !== '\n') e++
        let line = s.slice(p, e).join('')
        if (h.stripTabs) line = line.replace(/^\t+/, '')
        if (line === h.delim) {
          h.bodyEnd = p
          for (let k = p; k < e; k++) cls[k] = 't'
          p = e < n ? e + 1 : e
          if (e < n) cls[e] = 't'
          h.end = p
          found = true
          break
        }
        for (let k = p; k <= e && k < n; k++) cls[k] = h.quoted ? 'h' : 'u'
        p = e < n ? e + 1 : e
      }
      if (!found) {
        h.bodyEnd = n
        h.end = n
        problems.push('unterminated-heredoc')
      }
    }
    return p
  }

  const readDelimiter = (p) => {  // p at the first char of the delimiter word; returns { delim, quoted, end }
    let delim = ''
    let quoted = false
    while (p < n && !META.has(s[p])) {
      const ch = s[p]
      if (ch === "'") {
        quoted = true
        let e = p + 1
        while (e < n && s[e] !== "'") e++
        delim += s.slice(p + 1, e).join('')
        p = e < n ? e + 1 : e
      } else if (ch === '"') {
        quoted = true
        let e = p + 1
        while (e < n && s[e] !== '"') { if (s[e] === '\\' && e + 1 < n) e++; e++ }
        // bash: in "..." a backslash escapes only $ ` " \ newline (a backslash-newline is removed)
        delim += s.slice(p + 1, e).join('').replace(/\\([$`"\\\n])/g, (_, x) => (x === '\n' ? '' : x))
        p = e < n ? e + 1 : e
      } else if (ch === '\\' && p + 1 < n) {
        quoted = true
        delim += s[p + 1]
        p += 2
      } else {
        delim += ch
        p++
      }
    }
    return { delim, quoted, end: p }
  }

  while (i < n) {
    // the closing backtick of a backtick body ends every frame opened inside it (they are not understood: a problem)
    const live = liveBts()
    for (let b = live.length - 1; b >= 0; b--) {
      const [k, g] = live[b]
      if (i === g.bodyEnd) {
        while (stack.length - 1 > k) {
          const u = stack.pop()
          problems.push(u.sub ? 'unterminated-' + u.kind : 'unterminated-quote-' + u.kind)
          if (u.sub) { u.sub.inner[1] = i; u.sub.end = i }
        }
        break
      }
    }
    const f = top()
    const ch = s[i]
    const nx = i + 1 < n ? s[i + 1] : ''

    if (f.kind === "'") {  // inside '...' (only reached for $'...' via kind "$'")
      cls[i] = 'q'
      if (ch === "'") stack.pop()
      i++
      continue
    }
    if (f.kind === "$'") {
      cls[i] = 'a'
      if (ch === '\\' && i + 1 < n) { cls[i + 1] = 'a'; i += 2; continue }
      if (ch === "'") stack.pop()
      i++
      continue
    }
    if (f.kind === '"') {
      if (ch === '\\' && i + 1 < n && '$`"\\\n'.includes(nx)) {
        cls[i] = cls[i + 1] = nx === '\n' ? 'l' : 'e'
        i += 2
        continue
      }
      if (ch === '"') { cls[i] = 'd'; stack.pop(); i++; continue }
      if (ch === '$' && nx === '(') {
        if (s[i + 2] === '(' && !split.has(i)) { cls[i] = cls[i + 1] = cls[i + 2] = 'c'; openSubst('$((', i, i + 3); i += 3; continue }
        cls[i] = cls[i + 1] = 'c'; openSubst('$(', i, i + 2); i += 2; continue
      }
      if (ch === '$' && nx === '{') { cls[i] = cls[i + 1] = 'c'; openSubst('${', i, i + 2); i += 2; continue }
      if (ch === '`') { cls[i] = 'c'; openSubst('`', i, i + 1); i++; continue }
      cls[i] = 'd'
      i++
      continue
    }

    // a code frame: top, $(, (, <(, >(, `, $((, ((, ${
    if (f.kind === '`' && ch === '`') { cls[i] = 'c'; closeSubst(i, i + 1); i++; continue }
    if ((f.kind === '$((' || f.kind === '((')) {
      if (ch === '(') { f.depth++; i++; continue }
      if (ch === ')') {
        if (f.depth > 0) { f.depth--; i++; continue }
        if (nx === ')') { closeSubst(i, i + 2); i += 2; continue }
        return { retry: f.sub.start }  // Klodel 42854 matrix: $((a) ) and ((a) ) run a
      }
    }
    if (f.kind === '${' && ch === '}') { closeSubst(i, i + 1); i++; continue }
    if (ch === ')' && ['$(', '(', '<(', '>('].includes(f.kind)) { closeSubst(i, i + 1); i++; continue }

    // card f7d4ead8 (oracle matrix): inside a backtick an escaped backtick opens a nested command substitution, and
    // the next escaped backtick closes it; bash runs the command in it (echo `a \`b\`` runs b). A third level
    // (\\\`) is not modelled.
    if (ch === '\\' && nx === '`' && f.kind === '`') {
      cls[i] = cls[i + 1] = 'c'
      if (f.nested) closeSubst(i, i + 2)
      else openSubst('`', i, i + 2, true)
      i += 2
      continue
    }
    if (ch === '\\') {
      if (i + 1 < n) { cls[i] = cls[i + 1] = nx === '\n' ? 'l' : 'e'; i += 2 } else { cls[i] = 'e'; i++ }
      continue
    }
    if (ch === "'") { cls[i] = 'q'; stack.push({ kind: "'" }); i++; continue }
    if (ch === '$' && nx === "'") { cls[i] = cls[i + 1] = 'a'; stack.push({ kind: "$'" }); i += 2; continue }
    if (ch === '"') { cls[i] = 'd'; stack.push({ kind: '"' }); i++; continue }
    if (ch === '$' && nx === '"') { cls[i] = cls[i + 1] = 'd'; stack.push({ kind: '"' }); i += 2; continue }
    // Viktor 42794 HIGH 1: inside ${ }, $(( )) and (( )) a '#' is never a comment (bash and zsh, measured): it is
    // parameter or arithmetic text, and the frame closes at its own closer
    if (ch === '#' && !NO_COMMENT_KINDS.has(f.kind) && (i === 0 || WORD_START_BEFORE.has(s[i - 1]) && cls[i - 1] !== 'e' && !wordCloser.has(i - 1))) {
      // a comment inside a backtick ends at the closing backtick: bash cuts the body out first (echo `a #` ; b runs b)
      let btEnd = n
      for (const [, g] of liveBts()) if (g.bodyEnd < btEnd) btEnd = g.bodyEnd
      while (i < n && s[i] !== '\n' && i !== btEnd && !(f.kind === '`' && s[i] === '`')) { cls[i] = 'm'; i++ }
      continue
    }
    if (ch === '$' && nx === '(') {
      if (s[i + 2] === '(' && !split.has(i)) { openSubst('$((', i, i + 3); i += 3; continue }
      openSubst('$(', i, i + 2); i += 2; continue
    }
    if (ch === '$' && nx === '{') { openSubst('${', i, i + 2); i += 2; continue }
    if (ch === '`') { openSubst('`', i, i + 1); i++; continue }
    if ((ch === '<' || ch === '>') && nx === '(') { openSubst(ch + '(', i, i + 2); i += 2; continue }
    if (ch === '(' && f.kind !== '${') {
      if (nx === '(' && !split.has(i)) { openSubst('((', i, i + 2); i += 2; continue }
      openSubst('(', i, i + 1); i++; continue
    }
    if (ch === '<' && nx === '<' && s[i + 2] !== '<' && !['${', '$((', '(('].includes(f.kind)) {
      let p = i + 2
      const stripTabs = s[p] === '-'
      if (stripTabs) p++
      while (p < n && (s[p] === ' ' || s[p] === '\t')) p++
      const d = readDelimiter(p)
      if (d.delim === '') { i = p; continue }  // `<<` with no word: a syntax error, left as code
      if (f.kind !== 'top') {
        // inside a substitution bash 3.2 finds the closer first, bash 5 and zsh read the body first (measured with
        // bash, card fae0712e): no body is taken, its lines stay code, and the text is marked not understood
        problems.push('heredoc-in-subst')
        i = d.end
        continue
      }
      const h = { op: i, opEnd: d.end, delim: d.delim, quoted: d.quoted, stripTabs, bodyStart: n, bodyEnd: n, end: n }
      heredocs.push(h)
      pending.push(h)
      i = d.end
      continue
    }
    if (ch === '<' && nx === '<' && s[i + 2] === '<') { i += 3; continue }  // here-string: an operator, no body
    if (ch === '\n' && pending.length) { i = readHeredocBodies(i + 1); continue }
    i++
  }
  for (let k = stack.length - 1; k > 0; k--) {
    const f = stack[k]
    problems.push(f.sub ? `unterminated-${f.kind}` : `unterminated-quote-${f.kind}`)
  }
  if (pending.length) { readHeredocBodies(n); }
  const out = { cls: cls.join(''), problems, heredocs, substs, segments: segmentsOf(s, cls.join(''), substs) }
  // the code points, for words(): not enumerable, so the result's JSON (golden, tests) is unchanged
  Object.defineProperty(out, 'chars', { value: s })
  Object.defineProperty(out, 'text', { value: text })
  return out
}

function segmentsOf(s, cls, substs) {
  // ONE pass with a stack of open frames (substs is in start order and properly nested): linear in the text plus
  // the substitutions. A char belongs to the innermost frame whose inner range holds it; a frame's opener and
  // closer chars belong to none. A nested $( ) ` ` <( ) >( ) $(( )) ${ } is word content of the frame it sits in
  // (it runs or expands as that command's argument); a bare ( ) or (( )) is its own command.
  const n = s.length
  const out = []
  const mk = (fr, depth) => ({ fr, depth, frame: fr < 0 ? 'top' : substs[fr].kind, start: -1, last: -1 })
  const flush = (f) => {
    if (f.start >= 0) out.push({ start: f.start, end: f.last + 1, depth: f.depth, frame: f.frame, frameAt: f.fr })
    f.start = -1
    f.last = -1
  }
  const stack = [mk(-1, 0)]
  let k = 0
  for (let p = 0; p < n; p++) {
    while (stack.length > 1 && p >= substs[stack[stack.length - 1].fr].end) flush(stack.pop())
    while (k < substs.length && substs[k].start === p) {
      const y = substs[k]
      const parent = stack[stack.length - 1]
      if (y.kind !== '(' && y.kind !== '((') {
        if (parent.start < 0) parent.start = y.start
        parent.last = Math.max(parent.last, y.end - 1)
      }
      stack.push(mk(k, stack.length))
      k++
    }
    const f = stack[stack.length - 1]
    if (f.fr >= 0 && (p < substs[f.fr].inner[0] || p >= substs[f.fr].inner[1])) continue  // opener / closer
    const c = cls[p]
    if (c === 'h' || c === 'u' || c === 't' || c === 'm') { if (c !== 'm') flush(f); continue }
    if (c === 'c' && SEP.has(s[p]) && !redirAmp(s, cls, p)) { flush(f); continue }
    if (c === 'c' && (s[p] === ' ' || s[p] === '\t')) continue
    if (f.start < 0) f.start = p
    f.last = Math.max(f.last, p)
  }
  while (stack.length > 0) flush(stack.pop())
  return out.sort((a, b) => a.start - b.start || a.depth - b.depth)
}

function redirAmp(s, cls, p) {  // `&` of `>&`, `<&`, `&>` (a redirection, no separator)
  if (s[p] !== '&') return false
  if (p > 0 && (s[p - 1] === '>' || s[p - 1] === '<') && cls[p - 1] === 'c') return true
  return p + 1 < s.length && s[p + 1] === '>' && (p === 0 || s[p - 1] !== '&')
}

export function words(text, lx, seg) {
  const s = lx.text === text && lx.chars ? lx.chars : Array.from(text)  // one Array.from per lex, not per segment
  const cls = lx.cls
  const out = []
  let cur = null
  let inDq = false   // inside a "..." / $"..." of the current word
  let aState = 0     // $'...': 0 outside, 1 saw the $, 2 inside
  let aEsc = false
  let aBuf = ''
  const endA = () => { if (aState === 2) cur.text += ansiC(aBuf); aState = 0; aEsc = false; aBuf = '' }
  const push = () => { if (cur) { endA(); out.push(cur); cur = null } inDq = false }
  // the substitutions inside this segment (a char in one is verbatim word text): a sweep, not a scan per char
  const inner = []
  let lo = 0
  let hi = lx.substs.length
  while (lo < hi) { const mid = (lo + hi) >> 1; if (lx.substs[mid].start < seg.start) lo = mid + 1; else hi = mid }  // substs in start order
  for (let j = lo; j < lx.substs.length && lx.substs[j].start < seg.end; j++) {
    const x = lx.substs[j]
    if (x.end <= seg.end && !(x.start === seg.start && x.end === seg.end)) inner.push(x)
  }
  let ix = 0
  let coverEnd = -1
  for (let p = seg.start; p < seg.end; p++) {
    const c = cls[p]
    const ch = s[p]
    while (ix < inner.length && inner[ix].start <= p) { coverEnd = Math.max(coverEnd, inner[ix].end); ix++ }
    const inNested = p < coverEnd
    if (c === 'c' && !inNested && (ch === ' ' || ch === '\t')) { push(); continue }
    if (c === 'l') continue  // a backslash-newline is removed, it makes no word
    if (!cur) cur = { text: '', start: p, end: p + 1, quoted: false, expands: false }
    cur.end = p + 1
    if (inNested) { cur.text += ch; cur.expands = true; continue }  // a substitution stays verbatim in its word
    if (c === 'a') {
      cur.quoted = true
      if (aState === 0) { aState = 1; continue }           // the $
      if (aState === 1) { aState = 2; continue }           // the opening quote
      if (aEsc) { aBuf += ch; aEsc = false; continue }
      if (ch === '\\') { aBuf += ch; aEsc = true; continue }
      if (ch === "'") { endA(); continue }                 // the closing quote
      aBuf += ch
      continue
    }
    if (c === 'q') { cur.quoted = true; if (ch !== "'") cur.text += ch; continue }
    if (c === 'd') {
      cur.quoted = true
      if (!inDq) { if (ch === '"') inDq = true; continue }  // the opener: " or the $ of $"
      if (ch === '"') { inDq = false; continue }           // the closer (an escaped one is class e)
      cur.text += ch
      continue
    }
    if (c === 'e') { cur.quoted = true; if (!isPairStart(s, cls, p)) cur.text += ch; continue }
    if ((ch === '$' || ch === '`') && (c === 'c')) cur.expands = true
    cur.text += ch
  }
  push()
  return out
}

const ANSI_SIMPLE = { a: '\x07', b: '\b', e: '\x1b', E: '\x1b', f: '\f', n: '\n', r: '\r', t: '\t', v: '\v', '\\': '\\', "'": "'", '"': '"', '?': '?' }

// the value of the inside of a $'...' (bash: ansi-c quoting). \xHH, \nnn give the code point, not a raw byte (an
// approximation both lexers share); a surrogate or out-of-range \u/\U gives U+FFFD; an unknown escape stays as is.
export function ansiC(raw) {
  const r = Array.from(raw)
  let out = ''
  let i = 0
  const cp = (v) => (v > 0x10ffff || (v >= 0xd800 && v <= 0xdfff) ? '\ufffd' : String.fromCodePoint(v))
  while (i < r.length) {
    const ch = r[i]
    if (ch !== '\\' || i + 1 >= r.length) { out += ch; i++; continue }
    const e = r[i + 1]
    if (Object.hasOwn(ANSI_SIMPLE, e)) { out += ANSI_SIMPLE[e]; i += 2; continue }
    if (e >= '0' && e <= '7') {
      let j = i + 1
      let v = ''
      while (j < r.length && v.length < 3 && r[j] >= '0' && r[j] <= '7') v += r[j++]
      out += cp(parseInt(v, 8) & 0xff)
      i = j
      continue
    }
    if (e === 'x' || e === 'u' || e === 'U') {
      const max = e === 'x' ? 2 : e === 'u' ? 4 : 8
      let j = i + 2
      let v = ''
      while (j < r.length && v.length < max && /^[0-9a-fA-F]$/.test(r[j])) v += r[j++]
      if (!v) { out += '\\' + e; i += 2; continue }
      out += cp(parseInt(v, 16))
      i = j
      continue
    }
    if (e === 'c' && i + 2 < r.length) { out += cp(r[i + 2].codePointAt(0) & 0x1f); i += 3; continue }
    out += '\\' + e
    i += 2
  }
  return out
}

function isPairStart(s, cls, p) {  // is s[p] the backslash that opens an e-pair? count the e-run before it
  let k = p
  while (k - 1 >= 0 && cls[k - 1] === 'e') k--
  return (p - k) % 2 === 0
}
