import { describe, it, expect } from 'vitest'
import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { lex, words, ansiC } from '../../scripts/lib/shell-lex.mjs'
import type { ShellLex as Lx, ShellWord as Word } from '../../scripts/lib/shell-lex.mjs'

// fae0712e (DREAM 11-15): ONE shell lexer for the command gates. The golden file is the contract the JS lexer
// and its Python twin (scripts/lib/shell_lex.py, tested by scripts/lib/shell_lex_test.py) must BOTH meet, so
// the two cannot drift apart. The semantic asserts below say in words what a gate relies on.


const GOLDEN = JSON.parse(readFileSync(join(__dirname, '..', '..', 'scripts', 'lib', 'shell-lex-golden.json'), 'utf8')).cases as Array<{ id: string; input: string; want: Record<string, unknown> }>

function answer(input: string) {
  const lx: Lx = lex(input)
  return {
    cls: lx.cls,
    problems: lx.problems,
    heredocs: lx.heredocs,
    substs: lx.substs,
    segments: lx.segments.map((sg) => ({ ...sg, words: (words(input, lx, sg) as Word[]).map((w) => [w.text, w.start, w.end, w.quoted, w.expands]) })),
  }
}

const segTexts = (input: string, depth?: number) => {
  const s = Array.from(input)
  const lx: Lx = lex(input)
  return lx.segments.filter((sg) => depth === undefined || sg.depth === depth).map((sg) => s.slice(sg.start, sg.end).join(''))
}
const argv = (input: string, k = 0) => {
  const lx: Lx = lex(input)
  return (words(input, lx, lx.segments.filter((sg) => sg.depth === 0)[k]) as Word[]).map((w) => w.text)
}

describe('shell-lex golden file', () => {
  it('has the cases', () => { expect(GOLDEN.length).toBeGreaterThanOrEqual(50) })
  for (const c of GOLDEN) {
    it(`${c.id}`, () => { expect(answer(c.input)).toEqual(c.want) })
  }
})

// Viktor 42697 condition 2: the lexer against a real bash. scripts/lib/shell-lex-oracle.json (generated by
// scripts/lib/shell-lex-oracle-gen.py, seed 1115) holds commands with marker commands and the markers bash RAN.
const ORACLE_ALL = JSON.parse(readFileSync(join(__dirname, '..', '..', 'scripts', 'lib', 'shell-lex-oracle.json'), 'utf8')).cases as Array<{ cmd: string; markers: string[]; ran: string[]; cell?: string; syntax?: boolean }>
// a matrix cell bash rejects as a syntax error (Klodel 42854) is checked at the gate level only (bash-egress-parser.test.ts)
const ORACLE = ORACLE_ALL.filter((c) => !c.syntax)
const ASSIGN = /^[A-Za-z_]\w*=/
function ranByLexer(cmd: string): Set<string> | null {  // same rule as ran_by_lexer in scripts/lib/shell_lex_test.py
  const lx: Lx = lex(cmd)
  if (lx.problems.length > 0) return null
  const chars = Array.from(cmd)
  const out = new Set<string>()
  for (const sg of lx.segments) {
    if (sg.frame === '$((' || sg.frame === '((') continue
    if (sg.frame === '${' && !/^[ \t\n|]$/.test(chars[lx.substs[sg.frameAt].inner[0]] ?? '')) continue
    const ws = words(cmd, lx, sg) as Word[]
    let i = 0
    while (i < ws.length && (ws[i].text === '{' || ws[i].text === '!' || (ASSIGN.test(ws[i].text) && !ws[i].quoted))) i++
    if (i < ws.length) out.add(ws[i].text)
  }
  return out
}

describe('shell-lex against a real bash (oracle)', () => {
  it('has the cases, and the lexer understands at least 90% of them', () => {
    expect(ORACLE.length).toBeGreaterThanOrEqual(300)
    expect(ORACLE.filter((c) => ranByLexer(c.cmd) === null).length * 10).toBeLessThanOrEqual(ORACLE.length)
  })
  it('a marker ran iff the lexer says it is a command word', () => {
    const bad: string[] = []
    for (const c of ORACLE) {
      const got = ranByLexer(c.cmd)
      if (got === null) continue  // the lexer does not understand the text: a gate fails closed there
      const pred = c.markers.filter((m) => got.has(m))
      if (JSON.stringify(pred) !== JSON.stringify(c.ran)) bad.push(`${JSON.stringify(c.cmd)} lexer=${pred} bash=${c.ran}`)
    }
    expect(bad).toEqual([])
  })
  it('the matrix: every frame x {# ; | & newline \' "} x {inside, right after} has a case (Klodel 42854, Viktor 42888)', () => {
    const m = ORACLE_ALL.filter((c) => c.cell)
    const cells = new Set(m.map((c) => c.cell!.replace(/\|in\d*$/, '|in')))
    expect(cells.size).toBe(20 * 7 * 2 - 7)  // 20 frames; top has no "after"
    // the only valid cells the lexer reports problems on (same list as scripts/lib/shell_lex_test.py): a quote left
    // open in a backtick body, a heredoc whose quoted delimiter word never ends its body
    expect(m.filter((c) => !c.syntax && ranByLexer(c.cmd) === null).map((c) => c.cell).sort()).toEqual(
      ["`|'|in", "\"`|'|in", '`|"|in', '"`|"|in', "heredoc-q|'|after", "heredoc-u|'|after", 'heredoc-q|"|after', 'heredoc-u|"|after'].sort())
  })
})

describe('shell-lex: what a gate relies on', () => {
  it('a quoted, escaped or commented separator never splits a command', () => {
    expect(segTexts("echo 'a;b' \"c|d\" e\\;f # g; h")).toEqual(["echo 'a;b' \"c|d\" e\\;f"])
  })
  it('a quoted heredoc body is inert and the command after the terminator is seen', () => {
    const t = "git commit -F - <<'MSG'\npython3 ./x.py\nMSG\nls"
    expect(segTexts(t)).toEqual(["git commit -F - <<'MSG'", 'ls'])
    const lx: Lx = lex(t)
    expect(lx.heredocs).toHaveLength(1)
    expect(lx.cls.includes('h')).toBe(true)
  })
  it('a heredoc operator in a quote, a comment or after a backslash is no operator', () => {
    for (const t of ['x -m "a <<\'E\'\n" ; ./m.py\nE', "true # <<'E'\n./m.py\nE", "x \\<<'E'\n./m.py\nE"]) {
      const lx: Lx = lex(t)
      expect(lx.heredocs).toEqual([])
      expect(segTexts(t)).toContain('./m.py')
    }
  })
  it('a heredoc inside a substitution is a problem and its lines stay code', () => {
    const t = "x $(true <<'M'\n) ; ./m.sh\nM"
    const lx: Lx = lex(t)
    expect(lx.problems).toContain('heredoc-in-subst')
    expect(segTexts(t)).toContain('./m.sh')
  })
  it('unterminated quotes, substitutions and heredocs are problems', () => {
    expect((lex("echo 'a") as Lx).problems.length).toBeGreaterThan(0)
    expect((lex('echo $(a') as Lx).problems.length).toBeGreaterThan(0)
    expect((lex("cat <<'E'\nx") as Lx).problems).toContain('unterminated-heredoc')
    expect((lex('echo ok') as Lx).problems).toEqual([])
  })
  it('a substitution is both part of its word and its own nested segment', () => {
    expect(segTexts('echo $(id) `who` <(ls)', 0)).toEqual(['echo $(id) `who` <(ls)'])
    expect(segTexts('echo $(id) `who` <(ls)', 1)).toEqual(['id', 'who', 'ls'])
    expect(argv('echo "a $(b) c"')).toEqual(['echo', 'a $(b) c'])
  })
  it('words: quote removal, backslash-newline removal and $\'..\' decoding', () => {
    expect(argv("a\"b\"'c'$'d'\\ e f")).toEqual(['abcd e', 'f'])
    expect(argv('git commit \\\n  -m x')).toEqual(['git', 'commit', '-m', 'x'])
    expect(argv("python3 $'\\x2e/m\\056py'")).toEqual(['python3', './m.py'])
    expect(argv('echo "a$" b')).toEqual(['echo', 'a$', 'b'])
  })
  it('ansiC decodes like bash (measured with /bin/bash 3.2)', () => {
    expect(ansiC('\\x2e/m\\056py\\cA\\q')).toBe('./m.py\u0001\\q')
    expect(ansiC("a\\'b\\\\")).toBe("a'b\\")
    expect(ansiC('\\ud800')).toBe('\ufffd')
  })
  it('stays linear on hostile input (card fae0712e: 1000 x f( took 23 s in JS, 255 s in Python before)', () => {
    // 40 000 open '(' (a per-character walk of the frame stack: about 6 s) and 11 000 split retries (Viktor 42888 LOW: 11.4 s)
    for (const t of ['f('.repeat(4000), '$(a '.repeat(1000), 'echo ${a:-$(b)} '.repeat(2000), '(a);'.repeat(3000),
      '(config '.repeat(40000), '`' + '(\n#x\n'.repeat(40000), 'echo $((a) ) '.repeat(11000)]) {
      const t0 = Date.now()
      const lx: Lx = lex(t)
      for (const sg of lx.segments) words(t, lx, sg)
      expect(Date.now() - t0, t.slice(0, 12)).toBeLessThan(2000)
    }
  })
  it('indices are code points', () => {
    const lx: Lx = lex("echo 'é😀' x")
    expect(lx.cls.length).toBe(Array.from("echo 'é😀' x").length)
  })
})
